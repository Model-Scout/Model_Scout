"""Stage D1c: collect Korea-related Kaggle datasets (official `kaggle` client, KAGGLE_API_TOKEN).

Kaggle search is loose ("korean" returns monthly gold prices first) and tags are noisy (a
restaurant-review set tagged finance/health), so selection is two-step:

  list     search terms -> usability >= MIN_USABILITY (documentation completeness; downloads are
           popularity, not quality, so there is no download floor)
  detail   metadata description >= MIN_DESCRIPTION_CHARS and Korea in the data: any mention in
           the title, subtitle, tags or description (a 63-country chart that includes South Korea
           is still useful to Korean users), except boilerplate that is not about the data
           ("not a resident of North Korea", a paper presented in Seoul).

Synthetic sets are kept but flagged; NER (16) later confirms or demotes the tag-derived tasks.
Rows use the HF stage-1 schema so 13/14/15/16 treat them like any ML dataset.

Outputs: data/kaggle_datasets_stage1.jsonl, data/public_catalog/kaggle_*.jsonl (gitignored cache),
data/readmes/kaggle/<owner>__<slug>.md
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import time
from pathlib import Path

AI_DIR = Path(__file__).resolve().parent
DATA_DIR = AI_DIR / "data"
OUTPUT = DATA_DIR / "kaggle_datasets_stage1.jsonl"
CATALOG_DIR = DATA_DIR / "public_catalog"
README_DIR = DATA_DIR / "readmes" / "kaggle"
SEARCH_TERMS = ("korean", "korea", "seoul", "hangul", "한국어", "한국")
MAX_PAGES = 25  # 20 rows a page; the long tail past ~500 per term is off-topic
MIN_USABILITY = 0.5
MIN_DESCRIPTION_CHARS = 200
REQUEST_PAUSE = 1.0
MAX_RETRIES = 4
KOREA_RE = re.compile(r"korea|seoul|hangul|busan|한국|서울|[가-힣]{2,}", re.I)
BOILERPLATE_RE = re.compile(
    r"[^.]*(?:resident of|sanction|embargo)[^.]*north korea[^.]*|"
    r"(?:conference|proceedings|symposium|workshop|sensys|ubicomp|acm|ieee)[^.]{0,160}seoul,?\s*(?:south\s*)?korea",
    re.I,
)
KOREAN_LANGUAGE_RE = re.compile(r"korean|한국어|[가-힣]{2,}", re.I)
SYNTHETIC_RE = re.compile(r"synthetic|합성 데이터|generated by (?:gpt|llm|chatgpt)", re.I)
HANGUL_RE = re.compile(r"[가-힣]")


def read_jsonl(path):
    if not path.exists():
        return []
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def write_jsonl(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + ".tmp")
    with open(temp, "w", encoding="utf-8") as f:
        f.writelines(json.dumps(row, ensure_ascii=False) + "\n" for row in rows)
    os.replace(temp, path)


def call(fn, *args, **kwargs):
    """Kaggle API call with a polite pause and backoff on rate limits / transient errors."""
    for attempt in range(MAX_RETRIES + 1):
        try:
            result = fn(*args, **kwargs)
            time.sleep(REQUEST_PAUSE)
            return result
        except Exception:
            if attempt == MAX_RETRIES:
                raise
            time.sleep(10 * 2**attempt)


def fetch_description(api, ref):
    import tempfile

    with tempfile.TemporaryDirectory() as folder:
        path = call(api.dataset_metadata, ref, path=folder)
        info = json.loads(Path(path).read_text(encoding="utf-8")).get("info") or {}
    return info.get("description")


def readme_language(text):
    letters = re.findall(r"[A-Za-z가-힣]", text)
    ratio = sum(bool(HANGUL_RE.match(c)) for c in letters) / len(letters) if letters else 0
    return "ko" if ratio >= 0.5 else "mixed" if ratio >= 0.2 else "en"


def keep(listing, meta):
    """Second-stage gate on the full metadata; returns the reason a dataset is dropped, or None."""
    description = meta.get("description") or ""
    if len(description) < MIN_DESCRIPTION_CHARS:
        return "short description"
    tags = " ".join(t.get("name", "") for t in listing.get("tags") or [])
    text = " ".join(
        [listing.get("title") or "", listing.get("subtitle") or "", tags, BOILERPLATE_RE.sub(" ", description)]
    )
    return None if KOREA_RE.search(text) else "no Korea in the data"


def build_row(listing, meta):
    ref = listing["ref"]
    owner, slug = ref.split("/", 1)
    title, subtitle = listing.get("title") or slug, (listing.get("subtitle") or "").strip()
    description = (meta.get("description") or "").strip()
    tags = [t.get("name") for t in listing.get("tags") or [] if t.get("name")]
    text = " ".join([title, subtitle, description])
    flags = ["synthetic"] if SYNTHETIC_RE.search(text) else []
    readme = (
        "\n".join(
            [
                f"# {title}",
                "",
                subtitle,
                "",
                description,
                "",
                f"출처: Kaggle ({ref})",
                f"태그: {', '.join(tags)}",
                f"라이선스: {listing.get('licenseName')}",
                f"수정일: {listing.get('lastUpdated')}",
            ]
        )
        + "\n"
    )
    README_DIR.mkdir(parents=True, exist_ok=True)
    readme_path = README_DIR / f"{owner}__{slug}.md"
    readme_path.write_text(readme, encoding="utf-8")
    return {
        "dataset_id": f"kaggle/{ref}",
        "source": "kaggle",
        "url": listing.get("url") or f"https://www.kaggle.com/datasets/{ref}",
        "sha": hashlib.sha256(readme.encode("utf-8")).hexdigest()[:40],
        "seed_reasons": ["kaggle_search"],
        "referenced_by_models": [],
        "downloads": listing.get("downloadCount"),
        "likes": listing.get("voteCount"),
        "gated": False,
        "languages": ["ko"] if KOREAN_LANGUAGE_RE.search(text) else [],
        "licenses": [listing["licenseName"]] if listing.get("licenseName") else [],
        "task_categories": [],
        "task_ids": [],
        "size_categories": [],
        "modalities": [],
        "formats": [],
        "tags": tags,
        "description": subtitle or description[:300],
        "card_data": {"pretty_name": title},
        "readme_path": readme_path.relative_to(AI_DIR).as_posix(),
        "readme_language": readme_language(text),
        "readme_chars": len(readme),
        "usability": listing.get("usabilityRating"),
        "total_bytes": listing.get("totalBytes"),
        "last_modified": listing.get("lastUpdated"),
        "quality_flags": flags,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--refresh", action="store_true", help="re-run searches and metadata calls")
    parser.add_argument("--self-check", action="store_true")
    args = parser.parse_args()
    if args.self_check:
        return self_check()

    from dotenv import load_dotenv

    load_dotenv(".env")  # KAGGLE_API_TOKEN must be set before the client is imported
    from kaggle.api.kaggle_api_extended import KaggleApi

    api = KaggleApi()
    api.authenticate()

    listing_path = CATALOG_DIR / "kaggle_listing.jsonl"
    if args.refresh or not listing_path.exists():
        found = {}
        for term in SEARCH_TERMS:
            for page in range(1, MAX_PAGES + 1):
                rows = [r.to_dict() for r in call(api.dataset_list, search=term, page=page)]
                if not rows:
                    break
                found.update({r["ref"]: r for r in rows})
            print(f"[kaggle] '{term}': {len(found)} unique so far", flush=True)
        write_jsonl(listing_path, list(found.values()))
    listings = read_jsonl(listing_path)
    candidates = [r for r in listings if (r.get("usabilityRating") or 0) >= MIN_USABILITY]

    # Metadata is cached per ref + lastUpdated, so a rerun only asks for changed datasets.
    meta_path = CATALOG_DIR / "kaggle_metadata.jsonl"
    cache = {(m["ref"], m["lastUpdated"]): m for m in read_jsonl(meta_path)}
    for listing in candidates:
        key = (listing["ref"], listing.get("lastUpdated"))
        if key not in cache:
            cache[key] = {"ref": key[0], "lastUpdated": key[1], "description": fetch_description(api, key[0])}
    write_jsonl(meta_path, list(cache.values()))

    rows, dropped = [], dict[str, int]()
    for listing in candidates:
        meta = cache[(listing["ref"], listing.get("lastUpdated"))]
        reason = keep(listing, meta)
        if reason:
            dropped[reason] = dropped.get(reason, 0) + 1
        else:
            rows.append(build_row(listing, meta))
    write_jsonl(OUTPUT, rows)
    print(
        json.dumps(
            {
                "listed": len(listings),
                "passed_list_filter": len(candidates),
                "kept": len(rows),
                "dropped": dropped,
                "synthetic_flagged": sum(bool(r["quality_flags"]) for r in rows),
            },
            ensure_ascii=False,
        ),
        f"-> {OUTPUT}",
    )


def self_check():
    korean = {"title": "KR3: Korean Restaurant Reviews", "tags": [{"name": "nlp"}]}
    assert keep(korean, {"description": "x" * 250}) is None
    assert (
        keep({"title": "Monthly Gold Prices", "tags": [{"name": "finance"}]}, {"description": "gold " * 60})
        == "no Korea in the data"
    )
    charts = {"description": "Top 50 songs of 63 countries: Spain, South Korea, Sweden. " + "daily chart data " * 20}
    assert keep({"title": "Spotify Daily Top 50", "tags": []}, charts) is None  # Korea is in the data
    survey = {
        "description": "Survey answers. " * 20
        + "You are not a resident of Crimea, Cuba, Iran, Syria, North Korea, or Sudan."
    }
    assert keep({"title": "ML Survey", "tags": []}, survey) == "no Korea in the data"
    cited = {"description": "Activity sensor logs. " * 20 + "In Proc. ACM SenSys 2015, Seoul, Korea."}
    assert keep({"title": "HAR Dataset", "tags": []}, cited) == "no Korea in the data"
    assert (
        keep({"title": "Samsung Stock", "tags": []}, {"description": "Seoul-listed. Korea Exchange. Korean won. " * 5})
        is None
    )
    assert keep(korean, {"description": "short"}) == "short description"
    assert keep({"title": "Reviews", "tags": [{"name": "korea"}]}, {"description": "y" * 250}) is None
    assert readme_language("한국어 리뷰 데이터셋") == "ko" and readme_language("English only") == "en"
    assert SYNTHETIC_RE.search("This synthetic dataset") and not SYNTHETIC_RE.search("real reviews")
    print("19_collect_kaggle_datasets ok")


if __name__ == "__main__":
    main()
